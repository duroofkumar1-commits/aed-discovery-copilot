records = list(REAL_RECORDS)
next_objectid = 30000
random.shuffle(BUILDING_TYPES)

for i, (name, lat, lon) in enumerate(NEIGHBOURHOODS):
    n_aeds = random.randint(4, 8)
    for j in range(n_aeds):
        template_name, hours, desc = random.choice(BUILDING_TYPES)
        building = template_name.format(n=name)
        d_lat = random.uniform(-0.006, 0.006)
        d_lon = random.uniform(-0.006, 0.006)
        lat_j = round(lat + d_lat, 7)
        lon_j = round(lon + d_lon, 7)
        postal = f"{random.randint(10, 82)}{random.randint(1000, 9999)}"
        floor = random.choice(["1", "1", "2", "B1", "G"])
        next_objectid += 1
        records.append(dict(
            OBJECTID=next_objectid,
            AED_ID=f"SYN-{next_objectid}",
            OPERATING_HOURS=hours,
            HOUSE_NUMBER=str(random.randint(1, 60)),
            ROAD_NAME=f"{name} Avenue {random.randint(1, 9)}",
            BUILDING_NAME=building,
            UNIT_NUMBER=None,
            POSTAL_CODE=postal,
            AED_LOCATION_DESCRIPTION=desc,
            AED_LOCATION_FLOOR_LEVEL=floor,
            LATITUDE=lat_j,
            LONGITUDE=lon_j,
            INC_CRC=f"SYN{next_objectid:08d}",
            FMEL_UPD_D="20260101000000",
            SOURCE="synthetic",
        ))

for r in records:
    r.setdefault("SOURCE", "real_sample")

features = []
for r in records:
    props = {k: v for k, v in r.items() if k not in ("LATITUDE", "LONGITUDE")}
    features.append({
        "type": "Feature",
        "geometry": {"type": "Point", "coordinates": [r["LONGITUDE"], r["LATITUDE"]]},
        "properties": props,
    })

geojson = {
    "type": "FeatureCollection",
    "name": "AED_LOCATIONS_DEV_SAMPLE",
    "_notice": ("Development sample only. 14 features are real (SOURCE=real_sample, "
                "Sentosa area, from the official data.gov.sg preview). All other "
                "features are SOURCE=synthetic, generated for prototype development. "
                "Replace with the organizer-frozen dataset before judging."),
    "features": features,
}

